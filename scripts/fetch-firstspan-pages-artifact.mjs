import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
const raw=execFileSync('git',['credential','fill'],{input:'protocol=https\nhost=github.com\nusername=cr3atL\n\n',encoding:'utf8',stdio:['pipe','pipe','pipe']});
const values=Object.fromEntries(raw.trim().split(/\r?\n/).map(l=>{const i=l.indexOf('=');return[l.slice(0,i),l.slice(i+1)];}));
const headers={Authorization:`Bearer ${values.password}`,Accept:'application/vnd.github+json','X-GitHub-Api-Version':'2022-11-28'};
const run=39930857079;
const list=await fetch(`https://api.github.com/repos/cr3atL/car-flycontral/actions/runs/${run}/artifacts`,{headers});
if(!list.ok)throw new Error('Artifact list HTTP '+list.status);
const data=await list.json(), artifact=data.artifacts.find(a=>a.name==='github-pages');
if(!artifact)throw new Error('Pages artifact missing');
const download=await fetch(artifact.archive_download_url,{headers});
if(!download.ok)throw new Error('Artifact download HTTP '+download.status);
const dir='docs/artifacts/coastal-art-'+run;
fs.mkdirSync(dir,{recursive:true});
const b=Buffer.from(await download.arrayBuffer());
fs.writeFileSync(dir+'/pages.zip',b);
const record={run,id:artifact.id,name:artifact.name,size:artifact.size_in_bytes,digest:artifact.digest,downloadedBytes:b.length,sourceCommit:'2381ea7fe6d37ac8707ca3b081872abf2dede918',path:dir+'/pages.zip'};
fs.writeFileSync(dir+'/provenance.json',JSON.stringify(record,null,2)+'\n');
console.log(JSON.stringify(record,null,2));
