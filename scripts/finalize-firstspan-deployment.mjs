import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const report=read('docs/coastal-art-deployment.json');
const cloud=read('docs/coastal-art-cloud-comparison.json');
const supervisor=read('docs/coastal-art-online-supervisor-play.json');
const native=read('docs/coastal-art-online-native-summary.json');
assert(report.pass&&cloud.pass&&native.pass);
assert.equal(report.resources.total,213);
assert.equal(report.resources.passed,213);
assert.equal(cloud.files,213);
assert.equal(native.sha256,supervisor.sha256);
for(const c of native.cases){
  const b=fs.readFileSync(c.file), r=JSON.parse(b);
  assert.equal(sha(b),c.sha256,c.file);
  assert(r.pass&&r.end.complete&&r.end.grounded,c.file);
  assert.equal(r.end.group,'far');
  assert(r.phases.some(p=>p.name==='bridge-contact'&&p.grounded&&p.group==='landing'));
  assert(r.phases.some(p=>p.name==='upper-contact'&&p.grounded&&p.group==='high'));
  assert.deepEqual(r.errors,[]);
  assert.deepEqual(r.networkErrors,[]);
  assert.deepEqual(r.observer.keys,['getState']);
  assert.equal(r.observer.dev,false);
  assert.equal(r.ordinaryEntry.readonly,false);
  assert.equal(r.bundleSHA256,supervisor.sha256);
  assert.equal(r.end.events.filter(e=>e.type==='crash'||e.type==='reset').length,0);
}
assert(supervisor.pc.retry.pass&&supervisor.mobileLayout.retry.pass);
assert.deepEqual(supervisor.consoleErrorsAndWarnings,[]);
report.cloudArtifact={file:'coastal-art-cloud-comparison.json',digest:cloud.digestVerified,pass:cloud.pass};
report.buildComparison={previousRootBase:'roadster-6L2jcyue.js',relativeBase:'roadster-BAcCjqFS.js',explanation:'Vite base path rewrites asset imports and chunk hashes. Independent --base=./ build matches cloud artifact and online files. Initial mismatch preserved in coastal-art-root-base-comparison.json.'};
report.ordinaryOnlinePlay={file:'coastal-art-online-supervisor-play.json',pcFirstBridge:true,mobile667FirstBridge:true,failuresPreserved:true,errors:[],physicalPhone:false};
report.nativeOnline={file:'coastal-art-online-native-summary.json',bundle:native.bundle,sha256:native.sha256,cases:native.cases.map(c=>({file:c.file,sha256:c.sha256,pass:c.pass,complete:c.end.complete,errors:c.errors,networkErrors:c.networkErrors}))};
report.tests={developer:186,supervisor:186,failures:0,cloudWorkflow:'Check game rules step succeeded'};
report.cleanup=supervisor.cleanup;
fs.writeFileSync('docs/coastal-art-deployment.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({commit:report.commit,resources:report.resources,cloudArtifact:report.cloudArtifact,ordinaryOnlinePlay:report.ordinaryOnlinePlay,nativeCases:report.nativeOnline.cases,pass:report.pass},null,2));
